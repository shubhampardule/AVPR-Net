const SCAN_JOB_TIMEOUT_MS = 10 * 60 * 1000;
const SCAN_QUEUE_VISIBILITY_TIMEOUT_SECONDS = 660;
const SCAN_RECORD_DEADLINE_MS = 25 * 60 * 1000;

if (SCAN_QUEUE_VISIBILITY_TIMEOUT_SECONDS * 1000 <= SCAN_JOB_TIMEOUT_MS ||
  SCAN_QUEUE_VISIBILITY_TIMEOUT_SECONDS * 1000 + SCAN_JOB_TIMEOUT_MS >= SCAN_RECORD_DEADLINE_MS) {
  throw new Error("Scan record deadline must allow queue redelivery and another full worker attempt");
}

module.exports = {
  SCAN_JOB_TIMEOUT_MS,
  SCAN_QUEUE_VISIBILITY_TIMEOUT_SECONDS,
  SCAN_RECORD_DEADLINE_MS,
};
